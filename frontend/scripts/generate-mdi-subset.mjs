// scripts/generate-mdi-subset.mjs
// 生成 @mdi/font 的图标子集 CSS（T12 / D3 降级路径：字体子集化）。
//
// 全量 materialdesignicons.css 约 408 kB（gzip 56 kB），其中绝大多数图标类
// 本项目从未使用。本脚本：
//   1. 扫描 src/**/*.{vue,ts,tsx} 中的 `mdi-<name>` 字面量（当前全部为静态
//      使用，无运行时拼接，已用 grep 断言验证）；
//   2. 从 @mdi/font/scss/_variables.scss 的 $mdi-icons 映射取 codepoint；
//   3. 写出 src/styles/mdi-icons.css：仅含 @font-face + 所用图标的
//      content 规则（约 75 个图标 < 5 kB）。
//
// 由 package.json 的 predev / prebuild 钩子自动执行，产物随源码图标变化
// 自动更新；未识别的图标名会在控制台告警并在产物中缺字形（便于发现漏网）。
import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const srcDir = join(root, 'src')
const variablesPath = join(root, 'node_modules/@mdi/font/scss/_variables.scss')
const outPath = join(srcDir, 'styles/mdi-icons.css')
const fontUrlWoff2 = '@mdi/font/fonts/materialdesignicons-webfont.woff2'
const fontUrlTtf = '@mdi/font/fonts/materialdesignicons-webfont.ttf'

/** 解析 $mdi-icons SCSS 映射 → { 图标名: 大写 codepoint } */
function parseIconMap(scss) {
  const map = new Map()
  const lines = scss.split('\n')
  let inMap = false
  for (const line of lines) {
    if (line.includes('$mdi-icons:')) {
      inMap = true
      continue
    }
    if (!inMap) continue
    if (line.trim().startsWith(');')) break
    const match = line.match(/^\s*"([\w-]+)":\s*([0-9A-Fa-f]+),?\s*$/)
    if (match) map.set(match[1], match[2].toUpperCase())
  }
  return map
}

/** 递归收集 src 下待扫描文件 */
function collectFiles(dir) {
  const files = []
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name)
    if (entry.isDirectory()) {
      files.push(...collectFiles(full))
    } else if (/\.(vue|ts|tsx)$/.test(entry.name)) {
      files.push(full)
    }
  }
  return files
}

/** 扫描源码中的 mdi-<name> 字面量（排除处于更长标识符中间的误匹配） */
function scanIconNames(files) {
  const used = new Set()
  for (const file of files) {
    const text = readFileSync(file, 'utf8')
    for (const match of text.matchAll(/(?<![\w-])mdi-[a-z0-9][a-z0-9-]*/g)) {
      used.add(match[0])
    }
  }
  return used
}

function main() {
  if (!existsSync(variablesPath)) {
    console.error('[mdi-subset] @mdi/font 未安装，跳过子集生成（回退全量样式）')
    process.exit(1)
  }
  const iconMap = parseIconMap(readFileSync(variablesPath, 'utf8'))
  if (iconMap.size === 0) {
    console.error('[mdi-subset] $mdi-icons 解析失败，跳过子集生成（回退全量样式）')
    process.exit(1)
  }
  const used = scanIconNames(collectFiles(srcDir))
  const missing = []
  const rules = []
  for (const name of [...used].sort()) {
    const codepoint = iconMap.get(name.slice('mdi-'.length))
    if (codepoint === undefined) {
      missing.push(name)
      continue
    }
    rules.push(`.mdi-${name.slice('mdi-'.length)}::before { content: "\\${codepoint}"; }`)
  }
  if (missing.length > 0) {
    console.warn('[mdi-subset] 以下图标名不在 @mdi/font 图标表中，请核对拼写:', missing.join(', '))
  }

  const css = `/* AUTO-GENERATED by scripts/generate-mdi-subset.mjs — 不要手改。
 * 覆盖 ${rules.length} 个图标（源码扫描 mdi-* 字面量），全量样式约 408 kB → 子集 < 5 kB。 */
@font-face {
  font-family: "Material Design Icons";
  src: url("${fontUrlWoff2}") format("woff2"), url("${fontUrlTtf}") format("truetype");
  font-weight: normal;
  font-style: normal;
  font-display: block;
}

/* 公共字体属性：与全量 materialdesignicons.css 保持一致，
   兼容 vuetify 渲染的 "mdi mdi-xxx" 与裸 "mdi-xxx" 两种类组合 */
.mdi::before,
.mdi-set,
.mdi:before,
[class^="mdi-"]:before,
[class*=" mdi-"]:before {
  display: inline-block;
  font: normal normal normal 24px/1 "Material Design Icons";
  font-size: inherit;
  text-rendering: auto;
  line-height: inherit;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}

${rules.join('\n')}
`
  mkdirSync(dirname(outPath), { recursive: true })
  writeFileSync(outPath, css, 'utf8')
  console.log(`[mdi-subset] 已生成 ${outPath}（${rules.length} 个图标）`)
}

main()
